# Offline developer helper; ordinary builds use the bundled shader assets.
set -eu

shader_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
qsb=${QSB:-qsb}
dxc=${DXC:-dxc}
for tool in glslangValidator spirv-val "$qsb" "$dxc"; do
    command -v "$tool" >/dev/null 2>&1 || {
        printf 'Missing shader compiler/validator: %s\n' "$tool" >&2
        exit 1
    }
done
shader_tmp=$(mktemp -d)
trap 'rm -rf "$shader_tmp"' EXIT HUP INT TERM

glslangValidator -V --target-env vulkan1.0 -S frag \
    -o "$shader_tmp/hyllian.spv" "$shader_dir/hyllian.frag"
spirv-val --target-env vulkan1.0 "$shader_tmp/hyllian.spv"
"$qsb" --msl 12 --hlsl 51 -o "$shader_tmp/hyllian.qsb" "$shader_dir/hyllian.frag"
"$qsb" -x msl,12 -o "$shader_tmp/hyllian.raw.msl" "$shader_tmp/hyllian.qsb"
"$qsb" -x hlsl,51 -o "$shader_tmp/hyllian.raw.hlsl" "$shader_tmp/hyllian.qsb"

awk '/^layout/ { exit } /^\/\// { print }' "$shader_dir/hyllian.frag" \
    > "$shader_tmp/hyllian.msl"
printf '\n// Generated by Qt Shader Baker/SPIRV-Cross; do not edit.\n\n' \
    >> "$shader_tmp/hyllian.msl"
# Normalize the compiler's extra empty EOF line, keeping one final newline.
sed '${/^$/d;}' "$shader_tmp/hyllian.raw.msl" >> "$shader_tmp/hyllian.msl"

awk '/^layout/ { exit } /^\/\// { print }' "$shader_dir/hyllian.frag" \
    > "$shader_tmp/hyllian.hlsl"
printf '\n// Generated by Qt Shader Baker/SPIRV-Cross; do not edit.\n// SDL fragment register spaces remapped by regenerate.sh.\n\n' \
    >> "$shader_tmp/hyllian.hlsl"
# Qt normalizes descriptor sets to space0. SDL's fragment resources require
# space2/space3. Keep TEXCOORD0/1 to match SDL's bundled tri_texture DXIL.
# Check every replacement so translator/interface changes cannot silently ship.
awk '
    { buffers += sub(/register\(b0, space0\)/, "register(b0, space3)") }
    { textures += sub(/register\(t0, space0\)/, "register(t0, space2)") }
    { samplers += sub(/register\(s0, space0\)/, "register(s0, space2)") }
    /v_color : TEXCOORD0/ { colors++ }
    /v_texCoord : TEXCOORD1/ { uvs++ }
    { print }
    END {
        if (buffers != 1 || textures != 1 || samplers != 1 || colors != 1 || uvs != 1)
            exit 1
    }
' "$shader_tmp/hyllian.raw.hlsl" >> "$shader_tmp/hyllian.hlsl"
# DXC performs DXIL validation by default. Do not disable validation with -Vd.
"$dxc" -T ps_6_0 -E main -HV 2021 -O3 -WX \
    -Fo "$shader_tmp/hyllian.dxil" "$shader_tmp/hyllian.hlsl"

cp "$shader_tmp/hyllian.spv" "$shader_dir/hyllian.spv"
cp "$shader_tmp/hyllian.msl" "$shader_dir/hyllian.msl"
cp "$shader_tmp/hyllian.hlsl" "$shader_dir/hyllian.hlsl"
cp "$shader_tmp/hyllian.dxil" "$shader_dir/hyllian.dxil"
