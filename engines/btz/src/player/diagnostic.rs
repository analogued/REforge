//! Fingerprint lookup for standalone diagnostic inputs.

pub fn prepare_image(mut bytes: Vec<u8>) -> Result<crate::image::StoryImage, crate::Error> {
    super::patches::prepare_diagnostic_for_play(&mut bytes);
    crate::image::StoryImage::from_dos_obj(bytes)
}

