//! Host presentation of the interpreter's BIOS bell; independent of VM timing.

use reforge_audio::{
    PIT_HZ,
    category::SoundCategory,
    render::{BlipRenderer, Config, MAX_LEVEL, SignalRenderer},
    speaker::PcSpeaker,
};
use reforge_sdl::audio::{
    Playback,
    queue::{Policy, Queue},
};
use std::time::Duration;

const RATE: u32 = 48_000;
const DIVISOR: u16 = 0x528;
const TONE_MS: u64 = 333;
const TAIL_MS: u64 = 20;

/// The presentation reference is DOSBox-X's INT10 teletype bell: PIT channel 2
/// mode 3, divisor 1320, enabled for 333 ms. These hardware parameters are from
/// https://dosbox-x.com/doxygen/html/int10__char_8cpp_source.html#l00787 .
/// PCM is independently generated by REforge's shared PIT/speaker and renderer.
fn samples(volume: u8) -> Result<Vec<i16>, String> {
    let generate = || -> Result<Vec<i16>, Box<dyn std::error::Error>> {
        let mut speaker = PcSpeaker::new(0, [false; 3]);
        let mut renderer = BlipRenderer::new(
            Config {
                clock_hz: PIT_HZ as u32,
                sample_rate: RATE,
                chunk_ticks: (PIT_HZ / 100) as u32,
            },
            0,
            0,
        )?;
        let mut pcm = Vec::new();
        let mut collect = |block: &[i16]| {
            pcm.extend_from_slice(block);
            Ok(())
        };
        let level = i16::try_from(i32::from(MAX_LEVEL) * i32::from(volume) / 100)?;
        for (port, value) in [
            (0x43, 0xb6),
            (0x42, DIVISOR as u8),
            (0x42, (DIVISOR >> 8) as u8),
            (0x61, 3),
        ] {
            if let Some(edge) = speaker.write_port(port, value)?.drive {
                renderer.level_at(edge.tick, if edge.high { level } else { 0 }, &mut collect)?;
            }
        }
        let end = (PIT_HZ * TONE_MS).div_ceil(1000);
        while speaker.pit().tick() < end {
            if let Some(edge) = speaker.advance_to(end)?.drive {
                renderer.level_at(edge.tick, if edge.high { level } else { 0 }, &mut collect)?;
            }
        }
        if let Some(edge) = speaker.write_port(0x61, 0)?.drive {
            renderer.level_at(edge.tick, 0, &mut collect)?;
        }
        renderer.finish_until(end + PIT_HZ * TAIL_MS / 1000, &mut collect)?;
        // Settle the resampler's tail smoothly before an idle output underrun.
        let fade = (RATE / 200) as usize;
        let start = pcm.len().saturating_sub(fade);
        let length = pcm.len() - start;
        for (index, sample) in pcm[start..].iter_mut().enumerate() {
            *sample = (i32::from(*sample) * (length - index - 1) as i32 / length as i32) as i16;
        }
        Ok(pcm)
    };
    generate().map_err(|error| error.to_string())
}

pub(crate) struct Player {
    host: Playback,
    queue: Queue,
    generation: u64,
    pcm: Vec<i16>,
    epoch: Option<Duration>,
    generated: u64,
    failed: bool,
}
impl Player {
    pub(crate) fn new(host: Playback) -> Result<Self, String> {
        // Bells are isolated interactive events, so they need less startup
        // prefill than continuous game audio. Queuing never blocks the VM.
        host.set_prefill(Duration::from_millis(10))?;
        if let Err(error) = host.start(RATE) {
            eprintln!("REforge: bell audio unavailable; game continues: {error}");
        }
        let queue = Queue::new(
            RATE,
            Policy {
                max_pending: Duration::from_secs(60),
                ..Policy::for_output(&host)
            },
        )?;
        let pcm = samples(host.settings().categories.get(SoundCategory::Effects))?;
        Ok(Self {
            generation: host.generation(),
            host,
            queue,
            pcm,
            epoch: None,
            generated: 0,
            failed: false,
        })
    }

    pub(crate) fn service(&mut self, bells: usize, now: Duration, paused: bool) {
        if self.failed && self.generation == self.host.generation() {
            return;
        }
        if let Err(error) = self.feed(bells, now, paused) {
            eprintln!("REforge: bell playback stopped; game continues: {error}");
            self.host.stop();
            self.generation = self.host.generation();
            self.failed = true;
        }
    }

    fn feed(&mut self, bells: usize, now: Duration, paused: bool) -> Result<(), String> {
        if self.generation != self.host.generation() {
            self.queue.reset(&mut self.host, 0)?;
            self.pcm = samples(self.host.settings().categories.get(SoundCategory::Effects))?;
            self.generation = self.host.generation();
            self.epoch = None;
            self.failed = false;
        }
        self.queue.set_paused(&mut self.host, paused)?;
        if !self.host.available() || !self.host.settings().enabled {
            return Ok(());
        }
        if bells != 0 {
            if self.epoch.is_none() {
                self.queue.reset(&mut self.host, 0)?;
                self.generated = 0;
                self.epoch = Some(now);
            }
            for _ in 0..bells {
                self.queue.push(self.generated, self.pcm.clone())?;
                self.generated += self.pcm.len() as u64;
            }
        }
        if let Some(epoch) = self.epoch {
            let position = now.saturating_sub(epoch).as_nanos() * u128::from(RATE) / 1_000_000_000;
            self.queue
                .service(&mut self.host, position.min(u128::from(u64::MAX)) as u64)?;
            if self.queue.pending_samples() == 0 && self.host.queued_samples()? == 0 {
                self.epoch = None;
            }
        }
        Ok(())
    }
}
impl Drop for Player {
    fn drop(&mut self) {
        self.host.stop();
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn bell_pcm_has_bios_pitch_duration_and_effects_gain() {
        let pcm = samples(100).unwrap();
        let expected = (u64::from(RATE) * (TONE_MS + TAIL_MS) / 1000) as usize;
        assert!(pcm.len().abs_diff(expected) <= 1);
        let start = RATE as usize / 20;
        let end = RATE as usize / 4;
        let cycles = pcm[start..end]
            .windows(2)
            .filter(|pair| pair[0] <= 0 && pair[1] > 0)
            .count();
        let measured = cycles as f64 * f64::from(RATE) / (end - start) as f64;
        let target = PIT_HZ as f64 / f64::from(DIVISOR);
        assert!(
            (measured - target).abs() < 6.0,
            "{measured} Hz instead of {target}"
        );
        let quiet = samples(25).unwrap();
        let energy = |s: &[i16]| {
            s[start..end]
                .iter()
                .map(|v| f64::from(*v).powi(2))
                .sum::<f64>()
        };
        assert!((energy(&quiet) / energy(&pcm) - 0.0625).abs() < 0.001);
        assert!(samples(0).unwrap().iter().all(|sample| *sample == 0));
        assert_eq!(pcm.last(), Some(&0));
    }

    #[test]
    fn bell_stream_finishes_restarts_and_obeys_audio_settings() {
        const TEST: &str = "sound::tests::bell_stream_finishes_restarts_and_obeys_audio_settings";
        const MARKER: &str = "REFORGE_BTZ_AUDIO_TEST";
        if std::env::var(MARKER).as_deref() != Ok(TEST) {
            let output = std::process::Command::new(std::env::current_exe().unwrap())
                .args(["--exact", TEST, "--test-threads=1"])
                .env(MARKER, TEST)
                .env("SDL_AUDIO_DRIVER", "dummy")
                .env("SDL_AUDIODRIVER", "dummy")
                .output()
                .unwrap();
            assert!(
                output.status.success(),
                "{}\n{}",
                String::from_utf8_lossy(&output.stdout),
                String::from_utf8_lossy(&output.stderr)
            );
            return;
        }
        let host = Playback::new(Default::default());
        let mut player = Player::new(host.clone()).unwrap();
        assert!(host.available());
        let origin = std::time::Instant::now();
        player.service(2, origin.elapsed(), false);
        let expected = player.pcm.len() * 2;
        assert!(host.queued_samples().unwrap() > 0);
        assert!(host.queued_samples().unwrap() < expected);
        assert!(player.queue.pending_samples() > 0);
        let deadline = origin + Duration::from_secs(3);
        while player.epoch.is_some() {
            player.service(0, origin.elapsed(), false);
            assert!(
                std::time::Instant::now() < deadline,
                "bell playback did not drain"
            );
            assert!(!player.failed);
            std::thread::sleep(Duration::from_millis(2));
        }
        assert_eq!(player.queue.stats().submitted, expected as u64);
        assert_eq!(player.queue.stats().expired, 0);
        player.service(1, origin.elapsed(), true);
        assert_eq!(host.queued_samples().unwrap(), 0);
        let pending = player.queue.pending_samples();
        player.service(0, origin.elapsed(), true);
        assert_eq!(player.queue.pending_samples(), pending);

        let mut settings = host.settings();
        settings.enabled = false;
        // A disabled endpoint discards requests instead of deferring stale bells.
        let disabled = Playback::new(settings);
        let mut muted = Player::new(disabled.clone()).unwrap();
        muted.service(1, Duration::ZERO, false);
        assert_eq!(muted.queue.pending_samples(), 0);
        assert_eq!(disabled.queued_samples().unwrap(), 0);
        assert!(!disabled.available());
    }
}
