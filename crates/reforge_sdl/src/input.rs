//! Modern host shortcuts, separate from reconstructed DOS keyboard processing.

use sdl3::{
    event::Event,
    keyboard::{Keycode, Mod, Scancode},
};
use std::time::{Duration, Instant};

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum HostShortcut {
    Quit,
    TogglePause,
}

/// Letter shortcuts follow the keyboard layout; Pause identifies its physical key.
pub fn host_shortcut(event: &Event) -> Option<HostShortcut> {
    let Event::KeyDown {
        scancode,
        keycode,
        keymod,
        repeat,
        ..
    } = event
    else {
        return None;
    };
    let control = Mod::LCTRLMOD | Mod::RCTRLMOD;
    let desktop = control | Mod::LALTMOD | Mod::RALTMOD | Mod::LGUIMOD | Mod::RGUIMOD;
    if *keycode == Some(Keycode::Q) && keymod.intersects(control) {
        Some(HostShortcut::Quit)
    } else if (*scancode == Some(Scancode::Pause) || *keycode == Some(Keycode::Pause))
        && !repeat
        && !keymod.intersects(desktop)
    {
        Some(HostShortcut::TogglePause)
    } else {
        None
    }
}

/// Correlates SDL event timestamps with the host scheduling clock. The SDL
/// sample lies between `host` and `host + span`; this is a measured bracket,
/// not a claim that the two clocks share an epoch or exact precision.
#[derive(Clone, Copy, Debug)]
pub struct EventClockSample {
    pub host: Instant,
    pub sdl_ns: u64,
    pub span: Duration,
}

/// Call after SDL initialization. This only measures clocks; it does not pump
/// events, translate their timestamps, or change an engine's timeline.
pub fn event_clock_sample() -> EventClockSample {
    let host = Instant::now();
    // SAFETY: SDL_GetTicksNS has no pointer arguments and is thread-safe. The
    // caller has initialized SDL; the return value uses SDL's event clock.
    let sdl_ns = unsafe { sdl3::sys::timer::SDL_GetTicksNS() };
    EventClockSample {
        host,
        sdl_ns,
        span: host.elapsed(),
    }
}

/// A host timeline that freezes while paused. Existing engine deadlines remain
/// in that timeline, preserving their remaining waits without catching up.
#[derive(Default)]
pub struct HostPause {
    started: Option<Instant>,
    elapsed: Duration,
    first_pause: Option<Instant>,
}

impl HostPause {
    pub fn toggle(&mut self, now: Instant) {
        self.first_pause.get_or_insert(now);
        if let Some(started) = self.started.take() {
            self.elapsed += now.duration_since(started);
        } else {
            self.started = Some(now);
        }
    }

    pub fn is_paused(&self) -> bool {
        self.started.is_some()
    }

    /// Translate current or queued host time without exceeding the platform's
    /// Instant range. An unrepresentable old event clamps to the first pause
    /// boundary; input epochs must still reject it using its original host time.
    pub fn now(&self, now: Instant) -> Instant {
        self.started
            .unwrap_or(now)
            .checked_sub(self.elapsed)
            .unwrap_or(self.first_pause.unwrap_or(now))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn press(scan: Scancode, key: Option<Keycode>, mods: Mod, repeat: bool) -> Event {
        Event::KeyDown {
            timestamp: 0,
            window_id: 1,
            which: 0,
            raw: 0,
            scancode: Some(scan),
            keycode: key,
            keymod: mods,
            repeat,
        }
    }

    #[test]
    fn shortcuts_follow_layout_and_leave_game_keys_and_desktop_combinations_alone() {
        for control in [Mod::LCTRLMOD, Mod::RCTRLMOD] {
            // Q may be generated by a different physical key on another layout.
            assert_eq!(
                host_shortcut(&press(Scancode::A, Some(Keycode::Q), control, false)),
                Some(HostShortcut::Quit)
            );
            assert_eq!(
                host_shortcut(&press(Scancode::Q, Some(Keycode::A), control, false)),
                None
            );
            assert_eq!(
                host_shortcut(&press(Scancode::Q, None, control, false)),
                None
            );
        }
        assert_eq!(
            host_shortcut(&press(Scancode::Q, Some(Keycode::Q), Mod::NOMOD, false)),
            None
        );
        assert_eq!(
            host_shortcut(&press(
                Scancode::Pause,
                Some(Keycode::Pause),
                Mod::NOMOD,
                false
            )),
            Some(HostShortcut::TogglePause)
        );
        for modifier in [
            Mod::LCTRLMOD,
            Mod::RCTRLMOD,
            Mod::LALTMOD,
            Mod::RALTMOD,
            Mod::LGUIMOD,
            Mod::RGUIMOD,
        ] {
            assert_eq!(
                host_shortcut(&press(
                    Scancode::Pause,
                    Some(Keycode::Pause),
                    modifier,
                    false
                )),
                None
            );
        }
        assert_eq!(
            host_shortcut(&press(
                Scancode::Pause,
                Some(Keycode::Pause),
                Mod::NOMOD,
                true
            )),
            None
        );
        for scan in [
            Scancode::Escape,
            Scancode::P,
            Scancode::F1,
            Scancode::Space,
            Scancode::Up,
        ] {
            assert_eq!(host_shortcut(&press(scan, None, Mod::NOMOD, false)), None);
        }
        assert_eq!(host_shortcut(&Event::Quit { timestamp: 0 }), None);
    }

    #[test]
    fn host_pause_preserves_deadlines_across_multiple_pauses() {
        let start = Instant::now();
        let mut pause = HostPause::default();
        let deadline = start + Duration::from_millis(100);
        pause.toggle(start + Duration::from_millis(20));
        assert!(pause.is_paused());
        assert_eq!(
            pause.now(start + Duration::from_secs(60)),
            start + Duration::from_millis(20)
        );
        pause.toggle(start + Duration::from_secs(60));
        assert!(!pause.is_paused());
        assert_eq!(
            deadline.duration_since(pause.now(start + Duration::from_secs(60))),
            Duration::from_millis(80)
        );
        pause.toggle(start + Duration::from_millis(60_010));
        pause.toggle(start + Duration::from_millis(90_010));
        assert_eq!(
            pause.now(start + Duration::from_millis(90_030)),
            start + Duration::from_millis(50)
        );
    }

    #[test]
    fn unrepresentable_old_events_clamp_without_moving_current_deadlines() {
        let start = Instant::now();
        // Find an Instant less than one second above this platform's lower
        // representable bound without assuming a particular clock epoch.
        let (mut low, mut high) = (0_u64, u64::MAX);
        while low < high {
            let middle = low + (high - low) / 2 + 1;
            if start.checked_sub(Duration::from_secs(middle)).is_some() {
                low = middle;
            } else {
                high = middle - 1;
            }
        }
        let oldest = start.checked_sub(Duration::from_secs(low)).unwrap();
        assert!(oldest.checked_sub(Duration::from_secs(2)).is_none());
        let mut pause = HostPause::default();
        pause.toggle(start);
        let resumed = start + Duration::from_secs(3);
        pause.toggle(resumed);
        assert_eq!(pause.now(oldest), start);
        assert_eq!(pause.now(resumed), start);
        assert_eq!(
            pause.now(resumed + Duration::from_secs(1)),
            start + Duration::from_secs(1)
        );
    }
}
